"""Original background music for DARK CITADEL (PSG channel C).

A tune is written as notes in eighths: 'D2' starts a note, '.' holds the
previous one for another eighth, '-' is a rest.  The data is pairs of
(note, ticks) with note 0 = rest, 1.. = semitones from C1; FFh loops.
One tick = 16 ms (the sound interrupt).
"""
import math

CLOCK = 1996800              # PSG clock (Hz)
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8,
         'A': 9, 'A#': 10, 'B': 11}
NNOTES = 48                  # C1 .. B4

TUNES = [
    # 0: odd floors - a driving bass figure in D minor, then a slow melody
    (9, """
     D2 D2 A2 D2 C3 D2 A2 F2   D2 D2 A2 D2 E3 F3 E3 C3
     A#1 A#1 F2 A#1 A2 A#1 F2 D2   A1 A1 E2 A1 C#3 E3 C#3 A2
     D3 . F3 . A3 . G3 F3   E3 . C3 . D3 . . -
     A#2 . D3 . F3 . E3 D3   C#3 . E3 . A2 . . -
     """),
    # 1: even floors - slow and sparse, E minor
    (11, """
     E2 . . B2 . . E3 .   D3 . . B2 . . G2 .   C3 . . G2 . . E2 .   B1 . . F#2 . . B2 .
     E2 . . B2 . . E3 .   F#3 . . E3 . . D3 .   C3 . B2 . A2 . G2 .   F#2 . . D#2 . . B1 .
     """),
    # 2: between floors - a calm arpeggio, A minor
    (12, """
     A2 C3 E3 A3 G3 E3 C3 E3   F2 A2 C3 F3 E3 C3 A2 C3
     D2 F2 A2 D3 C3 A2 F2 A2   E2 G#2 B2 E3 D3 B2 G#2 B2
     """),
    # 3: the warden - fast and driving, E minor
    (7, """
     E2 E2 G2 E2 A#2 E2 A2 G2   E2 E2 G2 E2 B2 A#2 A2 G2
     C3 C3 B2 A2 G2 . F#2 .     E2 . D#2 . B1 . D#2 .
     """),
    # 4: the last floor - a slow heartbeat in C minor, the line creeping down
    (10, """
     C2 . . C2 G1 . . -   C2 . . C2 G#1 . . -
     C2 . . C2 G1 . . -   D#2 . D2 . C#2 . C2 .
     G2 . . F#2 . . F2 .   D#2 . . D2 . . C2 .
     G#1 . . G1 . . F#1 .   G1 . . . - . . .
     """),
]


def note_index(tok):
    name, octv = tok[:-1], int(tok[-1])
    return (octv - 1) * 12 + NAMES[name] + 1


def compile_tune(eighth, text):
    ev = []
    for tok in text.split():
        if tok == '.':
            ev[-1][1] += eighth
        elif tok == '-':
            ev.append([0, eighth])
        else:
            n = note_index(tok)
            assert 1 <= n <= NNOTES, tok
            ev.append([n, eighth])
    for e in ev:
        assert e[1] < 256
    return ev


def periods():
    out = []
    for i in range(NNOTES):
        f = 440.0 * 2 ** ((i + 24 - 69) / 12)        # index 0 = C1 (MIDI 24)
        out.append(min(4095, int(round(CLOCK / 16 / f))))
    return out


def asm():
    d = ['; generated by tools/music.py - original background music']
    d.append('bgm_per:')
    p = periods()
    for i in range(0, NNOTES, 12):
        d.append('        defw ' + ','.join(str(v) for v in p[i:i + 12]))
    d.append('bgm_tbl:')
    for i in range(len(TUNES)):
        d.append('        defw bgm_t%d' % i)
    for i, (eighth, text) in enumerate(TUNES):
        d.append('bgm_t%d:' % i)
        ev = compile_tune(eighth, text)
        for j in range(0, len(ev), 8):
            d.append('        defb ' + ','.join('%d,%d' % (n, t) for n, t in ev[j:j + 8]))
        d.append('        defb 0FFh')
    return '\n'.join(d) + '\n'


if __name__ == '__main__':
    tot = 0
    for i, (e, t) in enumerate(TUNES):
        ev = compile_tune(e, t)
        tot += len(ev) * 2 + 1
        print('tune %d: %d events, %.1f s per loop' % (i, len(ev), sum(x[1] for x in ev) * 0.016))
    print('data %d bytes + %d period table' % (tot, NNOTES * 2))
