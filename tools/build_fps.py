"""Build DARK CITADEL: the low-RAM data (compressed), the game, the voice test.

  python tools/fps_gen.py
  python tools/build_fps.py
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build
import lz

ROOT = build.ROOT
# RAM_DATA: after the sprites (fps_gen.py writes it as the org of fps_ram.inc)
RAM_DATA = int(open(os.path.join(ROOT, 'src', 'fps_ram.inc')).read().split('org 0')[1][:4], 16)
RAM_TOP = 0x3900                 # map tables 3900h / 3A00h, edge table 3B00h / 3C00h,
                                 # row tables 3D00h / 3E00h, the stack (from 4000h)
EXPORT = ['tex_gun', 'tex_gunf', 'tex_axe', 'tex_axes', 'extra_tbl', 'voice_tbl',
          'voice_pri', 'bgm_per', 'bgm_tbl']


def main():
    bdir = os.path.join(ROOT, 'build')
    os.makedirs(bdir, exist_ok=True)
    binf = os.path.join(bdir, 'fps_ram.bin')
    mapf = os.path.join(bdir, 'fps_ram.map')
    r = subprocess.run(['zxbasm', os.path.join(ROOT, 'src', 'fps_ram.asm'), '-o', binf, '-M', mapf],
                       capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(binf):
        print(r.stdout, r.stderr)
        sys.exit(1)
    data = open(binf, 'rb').read()
    if RAM_DATA + len(data) > RAM_TOP:
        sys.exit('RAM data too large: %d bytes (up to %04X)' % (len(data), RAM_DATA + len(data)))
    labels = {}
    for line in open(mapf):
        a, _, n = line.strip().partition(': ')
        labels[n.strip().lstrip('.')] = int(a, 16)
    blob = lz.compress(data)
    assert lz.decompress(blob) == data
    out = ['; generated by tools/build_fps.py - do not edit',
           'RAM_DATA     equ 0%04Xh' % RAM_DATA]
    for n in EXPORT:
        out.append('%-12s equ 0%04Xh' % (n, labels[n]))
    out.append('ram_blob:                      ; %d bytes -> %d' % (len(data), len(blob)))
    for k in range(0, len(blob), 24):
        out.append('        defb ' + ','.join('0%02Xh' % v for v in blob[k:k + 24]))
    open(os.path.join(ROOT, 'src', 'fps_blob.inc'), 'w').write('\n'.join(out) + '\n')
    print('RAM data: %d bytes at %04X-%04X, stored as %d' %
          (len(data), RAM_DATA, RAM_DATA + len(data) - 1, len(blob)))
    build.build(os.path.join(ROOT, 'src', 'fps.asm'), os.path.join(ROOT, 'fps.cas'), 'CITADL', 'DARK CITADEL')
    build.build(os.path.join(ROOT, 'src', 'vtest.asm'), os.path.join(ROOT, 'vtest.cas'), 'VTEST', 'VOICE TEST')
    # what is used after the start must lie below the screens (8000h)
    for name in ('fps', 'vtest'):
        for line in open(os.path.join(bdir, name + '.map')):
            a, _, n = line.strip().partition(': ')
            if n.strip().lstrip('.') == 'rt_end':
                rt = int(a, 16)
        if rt > 0x8000:
            sys.exit('%s: the program proper ends at %04X, beyond 7FFFh' % (name, rt))
        print('%s: program proper 4000-%04X (%d bytes free below 8000h)' % (name, rt - 1, 0x8000 - rt))


if __name__ == '__main__':
    main()
