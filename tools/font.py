def font_mask(rowstr):
    # 3 pixels + 1 spacing pixel -> one byte (2 bits per pixel)
    m = 0
    for k, ch in enumerate(rowstr):
        if ch == '#':
            m |= 3 << (6 - 2 * k)
    return m
